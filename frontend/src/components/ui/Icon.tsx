export type IconName = keyof typeof PATHS;

/** All icon names, e.g. for a picker or a story. */
export const ICON_NAMES = Object.keys(PATHS) as IconName[];

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  /** Pixel size (width = height). Default 16. */
  size?: number;
  /** Accessible name; when omitted the icon is aria-hidden. */
  title?: string;
}

export function Icon({ name, size = 16, title, strokeWidth = 1.75, className, ...rest }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className ? `shrink-0 ${className}` : 'shrink-0'}
      {...(title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true })}
      {...rest}
    >
      {title && <title>{title}</title>}
      {PATHS[name]}
    </svg>
  );
}

/** Renders an IconName as <Icon>, or passes any other ReactNode through. */
export function renderIcon(icon: IconName | ReactNode, size: number, className?: string): ReactNode {
  if (typeof icon === 'string' && icon in PATHS) {
    return <Icon name={icon as IconName} size={size} className={className} />;
  }
  return icon;
}
